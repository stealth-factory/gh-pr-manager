'use strict';

// Generate the tap formula from the tagged version and the public release
// archives. Homebrew installs these exact bytes; it does not rebuild them.
// Ported from opscope's homebrew/formula.js; this one also covers Linux,
// because gh-pr-manager publishes Linux x86_64 and arm64 tarballs too.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');

const NAME = 'gh-pr-manager';
const REPO = 'https://github.com/stealth-factory/gh-pr-manager';
const TARGETS = {
  macArm: 'aarch64-apple-darwin',
  macIntel: 'x86_64-apple-darwin',
  linuxArm: 'aarch64-unknown-linux-gnu',
  linuxIntel: 'x86_64-unknown-linux-gnu',
};

function stableVersion(version) {
  if (typeof version !== 'string' || version.trim() !== version ||
      !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version)) {
    throw new Error('Expected a stable release version X.Y.Z');
  }
  return version.split('.').map(BigInt);
}

function newer(a, b) {
  const left = stableVersion(a);
  const right = stableVersion(b);
  for (let i = 0; i < 3; i++) {
    if (left[i] !== right[i]) return left[i] > right[i];
  }
  return false;
}

function archiveChecksum(artifacts, version, target) {
  const name = `${NAME}-v${version}-${target}.tar.gz`;
  const file = path.join(artifacts, name);
  const hash = crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
  const recorded = fs.readFileSync(`${file}.sha256`, 'utf8').trim();
  if (recorded !== `${hash}  ${name}`) throw new Error(`Checksum mismatch for ${name}`);
  const listed = spawnSync('tar', ['-tzf', file], { encoding: 'utf8' });
  if (listed.status !== 0) throw new Error(`Cannot list ${name}: ${listed.stderr}`);
  const entries = new Set(listed.stdout.trim().split('\n'));
  const root = name.replace(/\.tar\.gz$/, '');
  if (!entries.has(`${root}/${NAME}`)) throw new Error(`${name} is missing binary ${NAME}`);
  return hash;
}

function urlFor(version, target) {
  return `${REPO}/releases/download/v${version}/${NAME}-v${version}-${target}.tar.gz`;
}

function generateFormula(version, artifacts) {
  stableVersion(version);
  const sums = {};
  for (const [key, target] of Object.entries(TARGETS)) {
    sums[key] = archiveChecksum(artifacts, version, target);
  }
  return `# Generated by gh-pr-manager's homebrew/formula.js from the published release.
# Release: ${version}
class GhPrManager < Formula
  desc "Mouse-friendly terminal UI for browsing and managing GitHub pull requests"
  homepage "${REPO}"
  version "${version}"
  license "AGPL-3.0-or-later"

  on_macos do
    on_arm do
      url "${urlFor(version, TARGETS.macArm)}"
      sha256 "${sums.macArm}"
    end
    on_intel do
      url "${urlFor(version, TARGETS.macIntel)}"
      sha256 "${sums.macIntel}"
    end
  end

  on_linux do
    on_arm do
      url "${urlFor(version, TARGETS.linuxArm)}"
      sha256 "${sums.linuxArm}"
    end
    on_intel do
      url "${urlFor(version, TARGETS.linuxIntel)}"
      sha256 "${sums.linuxIntel}"
    end
  end

  def install
    bin.install "${NAME}"
    pkgshare.install "README.md", "LICENSE", "CHANGELOG.md"
  end

  def caveats
    <<~EOS
      Authenticates with GH_TOKEN / GITHUB_TOKEN, or the GitHub CLI (gh auth login).
      Optional settings live in ~/.config/gh-pr-manager/config.toml.
    EOS
  end

  test do
    assert_match "${NAME} #{version}", shell_output("#{bin}/${NAME} --version")
  end
end
`;
}

if (require.main === module) {
  const [version, artifacts, output, previous] = process.argv.slice(2);
  if (!version || !artifacts || !output) {
    throw new Error('Usage: node homebrew/formula.js VERSION ARTIFACTS OUTPUT [PREVIOUS_FORMULA]');
  }
  stableVersion(version);
  if (previous) {
    const match = fs.readFileSync(previous, 'utf8').match(/^# Release: ([^\n]+)$/m);
    if (!match) throw new Error(`Existing ${NAME} formula has no release marker`);
    if (newer(match[1], version)) {
      console.log(`Tap already has ${match[1]}; refusing to downgrade to ${version}`);
      process.exit(0);
    }
  }
  const generated = generateFormula(version, artifacts);
  if (previous) {
    const original = fs.readFileSync(previous, 'utf8');
    if (original.includes(`# Release: ${version}\n`) && original !== generated) {
      throw new Error('This version already has a different formula; refusing to replace it');
    }
  }
  fs.writeFileSync(output, generated);
}

module.exports = { generateFormula, stableVersion, newer, TARGETS, NAME };
